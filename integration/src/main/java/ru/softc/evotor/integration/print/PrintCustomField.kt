package ru.softc.evotor.integration.print

/**
 * Произвольное поле печатного документа.
 *
 * Wire-format - JSON, ключи поля: `key`, `title`, `value`.
 *
 * Промежуточные слои (relay) обязаны передавать эти поля получателю как есть:
 * без фильтрации, переименования, интерпретации и переупорядочивания. Ключ
 * ([key]) не имеет семантики для промежуточного слоя - значение приходит от
 * вызывающего приложения, отображение определяет получатель.
 */
data class PrintCustomField(
    /**
     * Ключ поля, по которому получатель его идентифицирует
     */
    val key: String,
    /**
     * Заголовок поля, выводимый получателем
     */
    val title: String,
    /**
     * Строковое значение поля
     */
    val value: String
)
